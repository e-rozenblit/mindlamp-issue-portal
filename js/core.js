      const goals = [];
      ["stops", "data", "cost"].forEach(k => calc.answers(rep, k).forEach(a => {
        if (Object.prototype.hasOwnProperty.call(M[k], a)) goals.push.apply(goals, M[k][a]);
      }));
      let p = 0;
      goals.forEach(g => { const ix = top.indexOf(g); if (ix >= 0) p = Math.max(p, 3 - ix); });
      return p;
